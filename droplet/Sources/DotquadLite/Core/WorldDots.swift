    /// Whether the cell at this column and row is land.
    public static func isLand(column: Int, row: Int) -> Bool {
        guard rows.indices.contains(row), column >= 0, column < columns else { return false }
        let line = rows[row].utf8
        return line[line.index(line.startIndex, offsetBy: column)] == UInt8(ascii: "#")
    }

    /// A place as a fraction of the map's width and height (0 at the top
    /// left), clamped to the map. Nil for coordinates that aren't on Earth.
    public static func point(latitude: Double, longitude: Double) -> (x: Double, y: Double)? {
        guard (-90...90).contains(latitude), (-180...180).contains(longitude) else { return nil }
        let x = (longitude + 180) / 360
        let y = (top - latitude) / (top - bottom)
        return (min(max(x, 0), 1), min(max(y, 0), 1))
    }
}
